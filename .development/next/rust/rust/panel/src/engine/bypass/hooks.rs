pub(super) use transport::{refresh_transport, TransportRefresh};

const HELPER: &str =
    include_str!("../../../../../internal/services/nfqws2/scripts/nfqueue-bypass.sh");
const MARKER: &str = "# nfqws2-strategy: reapply NFQUEUE bypass";

fn quote(path: &Path) -> io::Result<String> {
    let s = path
        .to_str()
        .ok_or_else(|| io::Error::other("некорректный путь hook"))?;
    Ok(format!("'{}'", s.replace('\'', "'\"'\"'")))
}

pub(super) fn helper(path: &Path) -> io::Result<()> {
    let old = files::read(path, 2 << 20)?;
    if old
        .as_deref()
        .is_some_and(|s| !s.starts_with("#!/bin/sh\n# Generated by nfqws2-strategy."))
    {
        return Err(io::Error::other(
            "NFQUEUE bypass helper was modified outside the panel",
        ));
    }
    files::write(path, HELPER, 0o755, old.as_deref())
}

pub(super) fn patched(old: &str, helper: &Path) -> io::Result<String> {
    let helper = quote(helper)?;
    let block = format!("{MARKER}\n[ -x {helper} ] && {helper} iptables >/dev/null 2>&1 || true\n[ -x {helper} ] && {helper} ip6tables >/dev/null 2>&1 || true\n");
    let mut lines = old.split_inclusive('\n');
    let mut pos = 0;
    if old.contains(MARKER) {
        while let Some(line) = lines.next() {
            if line.trim() == MARKER {
                let mut end = pos + line.len();
                for family in ["iptables", "ip6tables"] {
                    let raw = lines.next().ok_or_else(|| {
                        io::Error::other("NFQWS2 init has incomplete bypass hook")
                    })?;
                    let l = raw.trim();
                    if !l.starts_with("[ -x ")
                        || !l.contains(" ] && ")
                        || !l.ends_with(&format!(" {family} >/dev/null 2>&1 || true"))
                    {
                        return Err(io::Error::other("NFQWS2 init has unexpected bypass hook"));
                    }
                    end += raw.len();
                }
                return Ok(format!("{}{block}{}", &old[..pos], &old[end..]));
            }
            pos += line.len();
        }
        return Err(io::Error::other(
            "NFQWS2 init has unrecognized bypass marker",
        ));
    }
    for line in lines {
        pos += line.len();
        let trimmed = line.trim();
        if trimmed.split_whitespace().next() == Some("system_config")
            && !trimmed.contains("()")
            && !trimmed.ends_with('{')
            && line.ends_with('\n')
        {
            return Ok(format!("{}{block}{}", &old[..pos], &old[pos..]));
        }
    }
    Err(io::Error::other(
        "NFQWS2 init has no system_config post-start anchor",
    ))
}

pub(super) fn persist(
    dir: &Path,
    init: &Path,
    helper: &Path,
    platform: Platform,
    runner: &impl Runner,
    deadline: Instant,
) -> io::Result<()> {
    let old = files::read(init, 2 << 20)?.ok_or(io::ErrorKind::NotFound)?;
    let patched = patched(&old, helper)?;
    let h = quote(helper)?;
    let (path, body) = match platform {
        Platform::Entware => (
            dir.parent().ok_or_else(|| io::Error::other("нет каталога Entware"))?.join("ndm/netfilter.d/101-nfqws2-bypass.sh"),
            format!("#!/bin/sh\n[ \"${{table:-}}\" = mangle ] || exit 0\ncase \"${{type:-}}\" in iptables|ip6tables) ;; *) exit 0 ;; esac\n[ -x {h} ] || exit 0\n{h} \"$type\" >/dev/null || echo 'NFQUEUE bypass: Keenetic firewall reload failed' >&2\n")
        ),
        Platform::OpenWrt => {
            let i = quote(init)?;
            (dir.join("nfqws-bypass-fw4.sh"), format!("#!/bin/sh\n{i} firewall_iptables >/dev/null 2>&1 || true\n{i} firewall_ip6tables >/dev/null 2>&1 || true\n{h} iptables >/dev/null || echo 'NFQUEUE bypass: IPv4 firewall reload failed' >&2\n{h} ip6tables >/dev/null || echo 'NFQUEUE bypass: IPv6 firewall reload failed' >&2\n"))
        },
    };
    let previous = files::read(&path, 1 << 20)?;
    files::write(&path, &body, 0o755, previous.as_deref())?;
    if platform == Platform::OpenWrt {
        let path = path
            .to_str()
            .ok_or_else(|| io::Error::other("некорректный путь OpenWrt"))?;
        let fields = [
            ("", "include"),
            (".type", "script"),
            (".path", path),
            (".fw4_compatible", "1"),
        ];
        let changes = runner.run("uci", &["changes", "firewall"], deadline)?;
        let own_delta = |line: &str| {
            line.trim_start_matches(['-', '+'])
                .strip_prefix("firewall.nfqws2_bypass_fw4")
                .is_some_and(|tail| tail.is_empty() || tail.starts_with(['.', '=']))
        };
        let staged = changes.lines().any(own_delta);
        let other_edits = changes
            .lines()
            .any(|line| !line.is_empty() && !own_delta(line));
        let mut updates = Vec::new();
        for (suffix, val) in fields {
            let key = format!("firewall.nfqws2_bypass_fw4{suffix}");
            let current = runner.run("uci", &["-q", "get", &key], deadline);
            if current.as_deref().ok() != Some(val) {
                updates.push(format!("{key}={val}"));
            }
        }
        if staged || !updates.is_empty() {
            if other_edits {
                return Err(io::Error::other("В UCI есть несохранённые изменения firewall. Завершите их перед применением NFQUEUE bypass."));
            }
            for change in updates {
                runner.run("uci", &["set", &change], deadline)?;
            }
            runner.run("uci", &["commit", "firewall"], deadline)?;
        }
    }
    if patched != old {
        let mut backup = OsString::from(init);
        backup.push(".n2s-bak");
        files::backup(Path::new(&backup), &old)?;
        files::write(init, &patched, 0o755, Some(&old))?;
    }
    Ok(())
}
