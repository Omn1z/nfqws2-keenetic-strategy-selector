#[derive(Default)]
struct Data {
    enabled: bool,
    save_fails: bool,
    restore_fails: bool,
    ignore_write: bool,
    clients_fail: bool,
    calls: Vec<String>,
}
#[derive(Default)]
struct Fixture(Guard<Data>);
impl Execute for Fixture {
    async fn command(&self, arg: &str) -> io::Result<String> {
        let mut data = self.0.lock().unwrap();
        data.calls.push(arg.into());
        match arg {
            "show running-config"=>Ok(if data.enabled{CONFIG.replace("include Guest5G","include Guest5G\n    peer-isolation")}else{CONFIG.into()}),
            "show interface Bridge0"=>Ok(status()),
            "show associations" if data.clients_fail=>Err(invalid("fixture")),
            "show associations"=>Ok("station:\n      mac: 02:00:00:00:00:01\n       ap: WifiMaster1/AccessPoint1".into()),
            "show ip dhcp bindings"=>Ok("lease:\n       ip: 192.0.2.2\n      mac: 02:00:00:00:00:01\n hostname: fixture-client".into()),
            "interface Bridge0 peer-isolation"=>{if !data.ignore_write {data.enabled=true;}Ok(String::new())}
            "interface Bridge0 no peer-isolation" if data.restore_fails=>Err(invalid("fixture")),
            "interface Bridge0 no peer-isolation"=>{data.enabled=false;Ok(String::new())}
            "system configuration save" if std::mem::take(&mut data.save_fails)=>Err(invalid("fixture save")),
            "system configuration save"=>Ok(String::new()),
            _=>panic!("unexpected fixture command"),
        }
    }
}
fn fixture() -> Service<Fixture> {
    Service {
        platform: "keenetic",
        reason: "",
        backend: Default::default(),
        cache: Default::default(),
    }
}

#[derive(Default)]
struct Paused {
    fixture: Fixture,
    wrote: tokio::sync::Notify,
    resume: tokio::sync::Notify,
}
impl Execute for Paused {
    async fn command(&self, arg: &str) -> io::Result<String> {
        let value = self.fixture.command(arg).await?;
        if arg == "interface Bridge0 peer-isolation" {
            self.wrote.notify_one();
            self.resume.notified().await;
        }
        Ok(value)
    }
}
#[tokio::test]
async fn dropping_request_after_native_write_still_verifies_and_saves() {
    let s = Service {
        platform: "keenetic",
        reason: "",
        backend: Arc::new(Paused::default()),
        cache: Default::default(),
    };
    let rev = s.view().await.unwrap().revision;
    let api = s.owned();
    let request = tokio::spawn(async move { api.change(change(rev, true)).await });
    s.backend.wrote.notified().await;
    request.abort();
    let _ = request.await;
    s.backend.resume.notify_one();
    let view = tokio::time::timeout(Duration::from_secs(2), s.view())
        .await
        .unwrap()
        .unwrap();
    assert!(view.segments[0].enabled);
    assert!(s
        .backend
        .fixture
        .0
        .lock()
        .unwrap()
        .calls
        .iter()
        .any(|c| c == "system configuration save"));
}
fn change(revision: String, enabled: bool) -> Change {
    Change {
        segment: "Bridge0".into(),
        enabled,
        revision,
    }
}
#[tokio::test]
async fn accepts_the_go_revision_of_the_unchanged_wireless_segment() {
    // Generated by sha256(json.Marshal(arpblock.ParseKeeneticConfig(CONFIG))).
    let go_revision = "5af6db2e21c7324f908894fc06ba1d34faff4f29127850df7cd90d29f167ac90";
    let after_enable = "dcc980dfbba2dd66bab6c607ae06fe66113071816e7f38e856c025ba220697ad";
    let s = fixture();
    let view = s.view().await.unwrap();
    assert_eq!(view.revision, go_revision);
    let after = s.change(change(go_revision.into(), true)).await.ok().unwrap();
    assert!(after.segments[0].enabled);
    assert_eq!(after.revision, after_enable);
    assert_eq!(
        s.change(change(go_revision.into(), false)).await.err().unwrap().0,
        StatusCode::CONFLICT
    );
}

#[test]
fn go_revision_preserves_explicit_false_and_json_escaping() {
    let config = format!(
        "no isolate-private\n{}",
        CONFIG
            .replace("Guest network", "Guest <&>\u{2028}Guest\u{2029}")
            .replace("include Guest5G", "include Guest5G\n    no peer-isolation")
    );
    let topology = parse::topology(&config).unwrap();
    let go_revision = "9f202217a223e5ec0cbc4e1d6b847b63b089429b8971c54de53c5af365f998f8";
    assert_eq!(revision::token(&topology).unwrap(), go_revision);
    let without_secrets = config.replace("fixture-discarded", "other-discarded");
    assert_eq!(
        revision::token(&parse::topology(&without_secrets).unwrap()).unwrap(),
        go_revision
    );
}

#[test]
fn wifi_inventory_matches_go_mac_forms_across_native_tables() {
    let cfg = parse::topology(CONFIG).unwrap();
    let stations = concat!(
        "station:\n mac: 02-00-00-00-00-AB\n  ap: WifiMaster1/AccessPoint1\n",
        "station:\n mac: 0200.0000.00ab\n  ap: Guest5G\n",
        "station:\n mac: 02:00-00:00:00:cc\n  ap: Guest5G\n",
    );
    let leases = "lease:\n      mac: 0200.0000.00ab\n       ip: 192.0.2.10\n hostname: fixture";
    let clients = clients::clients(&cfg, stations, leases);
    assert_eq!(clients.len(), 1);
    assert_eq!(clients[0].mac, "02:00:00:00:00:ab");
    assert_eq!(clients[0].segment, "Bridge0");
    assert_eq!(clients[0].ip, "192.0.2.10");
    assert_eq!(clients[0].hostname, "fixture");
}

#[tokio::test]
async fn passive_inventory_caches_and_mutations_verify_then_save() {
    let s = fixture();
    let view = s.view().await.unwrap();
    assert_eq!(view.segments[0].name, "Дом Wi-Fi");
    assert!(view.segments[0].eligible);
    assert!(view.segments[0].home);
    assert_eq!(view.segments[0].ssids, ["Guest network"]);
    assert_eq!(view.clients[0].hostname, "fixture-client");
    assert_eq!(view.clients[0].segment, "Bridge0");
    assert!(!serde_json::to_string(&view)
        .unwrap()
        .contains("fixture-discarded"));
    assert_eq!(s.view().await.unwrap().revision, view.revision);
    assert_eq!(s.backend.0.lock().unwrap().calls.len(), 3);
    let mut tampered = change(view.revision.clone(), true);
    tampered.segment = "Bridge0 reboot".into();
    assert!(s.change(tampered).await.is_err());
    assert_eq!(
        s.change(change("0".repeat(64), true))
            .await
            .err()
            .unwrap()
            .0,
        409
    );
    let v = s.change(change(view.revision, true)).await.ok().unwrap();
    assert!(v.segments[0].enabled);
    assert!(s.backend.0.lock().unwrap().calls.windows(3).any(|w| w
        == [
            "interface Bridge0 peer-isolation",
            "show running-config",
            "system configuration save"
        ]));
    s.backend.0.lock().unwrap().clients_fail = true;
    let after = s.change(change(v.revision, false)).await.ok().unwrap();
    assert!(!after.segments[0].enabled);
    assert!(!after.reason.is_empty());
}
#[tokio::test]
async fn failed_or_unconfirmed_write_rolls_back_and_reports_rollback_failure() {
    for (ignore, restore_fails) in [(false, false), (false, true), (true, false)] {
        let s = fixture();
        let v = s.view().await.unwrap();
        {
            let mut f = s.backend.0.lock().unwrap();
            f.ignore_write = ignore;
            f.save_fails = !ignore;
            f.restore_fails = restore_fails;
        }
        let e = s.change(change(v.revision, true)).await.err().unwrap();
        assert!(e.1.contains(if restore_fails {
            "не подтверждён"
        } else {
            "восстановлена"
        }));
        assert_eq!(s.backend.0.lock().unwrap().enabled, restore_fails);
    }
}
#[test]
fn malformed_or_external_segments_are_rejected() {
    for cfg in [
        CONFIG.replace("rename Home", "rename Guest5G"),
        CONFIG.replace("interface Bridge0", "interface Bridge0 x"),
        CONFIG.replace("include Guest5G", "include Guest5G\n    include Guest5G"),
        CONFIG.replace(
            "security-level private",
            "security-level private\n    security-level public",
        ),
        CONFIG.replace("255.255.255.0", "255.0.255.0"),
        CONFIG.replace("Guest network", "Guest\\x00network"),
    ] {
        assert!(parse::topology(&cfg).is_err());
    }
    for (from, to) in [
        ("security-level private", "security-level public"),
        ("include Guest5G", "ip global 1"),
        ("192.0.2.1 255.255.255.0", "192.0.2.2 255.255.255.0"),
        ("rename Home", "rename Other"),
    ] {
        let parsed = parse::topology(&CONFIG.replace(from, to)).unwrap();
        assert!(parsed.bridges[0].confirm(&status()).is_err());
    }
    let cfg = parse::topology(CONFIG).unwrap();
    let b = &cfg.bridges[0];
    assert!(!b.isolation.unwrap_or(false));
    assert!(b
        .confirm(&format!("{}{:>26}: wrong\n", status(), "id"))
        .is_ok());
    for st in [
        status().replace("global: no", "global: yes"),
        status().replace("global: no", "global: unknown"),
        status().replace("type: Bridge", "type: Ethernet"),
        format!("{}{:>17}: Bridge0\n", status(), "id"),
    ] {
        assert!(b.confirm(&st).is_err());
    }
}
#[tokio::test]
async fn http_requires_an_explicit_boolean_revision_and_bounded_request() {
    let root = tempfile::tempdir().unwrap();
    let cfg = Config {
        data_dir: root.path().display().to_string(),
        ..Config::from_resolver(&Resolver::new_at(root.path()))
    };
    let app = crate::http::router(crate::http::AppState::open(cfg, root.path(), true).unwrap());
    for (body, status) in [
        (r#"{"segment":"Bridge0"}"#.into(), 400),
        ("{}".repeat(2048), 413),
        (
            r#"{"segment":"Bridge0","enabled":null,"revision":"x"}"#.into(),
            400,
        ),
        (
            r#"{"segment":"Bridge0","enabled":false,"revision":"x","extra":1}"#.into(),
            400,
        ),
    ] {
        let r = app
            .clone()
            .oneshot(
                Request::builder()
                    .method("POST")
                    .uri("/api/arp-block/isolation")
                    .body(Body::from(body))
                    .unwrap(),
            )
            .await
            .unwrap();
        assert_eq!(r.status(), status);
        assert_eq!(r.headers()[header::CACHE_CONTROL], "no-store");
        assert!(to_bytes(r.into_body(), 4096).await.is_ok());
    }
}
