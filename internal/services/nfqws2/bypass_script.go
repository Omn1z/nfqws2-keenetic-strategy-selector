// The panel owns a helper separate from the upstream nfqws-bypass.sh. The
// upstream Entware helper resolves domains and runs iptables once per address,
// which can take minutes on a router. This POSIX-sh helper consumes the panel's
// resolved-IP cache and stages address sets before atomically replacing one
// dedicated mangle chain. Routers without kernel ipset support keep bulk rules.
const generatedBypassScript = `#!/bin/sh
# Generated by nfqws2-strategy. Do not edit: upgraded with the panel.
set -u
set -f

CMD="${1:-iptables}"
case "$CMD" in
  iptables|ip6tables) ;;
  *) echo "usage: $0 {iptables|ip6tables}" >&2; exit 2 ;;
esac

TABLE=mangle
BYPASS=nfqws2_bypass
POST=nfqws_post
PRE=nfqws_pre
BASE=$(CDPATH= cd -- "$(dirname -- "$0")" 2>/dev/null && pwd)
LIST="$BASE/lists"
RESTORE="${CMD}-restore"
case "$CMD" in
  iptables) SET=n2s_nfqb4; FAMILY=inet ;;
  ip6tables) SET=n2s_nfqb6; FAMILY=inet6 ;;
esac
STAGE="${SET}_new"
PROBE=n2s_nfqb_$$

# Upstream omits IPv6 firewall chains when IPV6_ENABLED=0.  An absent IPv6
# family is normal; IPv4 below must still validate its bypass jumps.
if [ "$CMD" = ip6tables ] &&
   ! $CMD -w -t "$TABLE" -S "$POST" >/dev/null 2>&1 &&
   ! $CMD -w -t "$TABLE" -S "$PRE" >/dev/null 2>&1; then
  exit 0
fi

# Hooks, startup and manual refresh may overlap. Entware does not always ship
# flock. Never steal a live or incompletely initialized lock; fail boundedly.
umask 077
# The lock must be shared even if ndm and the panel have different TMPDIRs.
lock="/tmp/nfqws-bypass-$CMD.lock"
attempt=0
while ! mkdir "$lock" 2>/dev/null; do
  # Reaping a PID reported dead races with a new owner's mkdir. Leave stale
  # locks for explicit recovery (or reboot), never delete another owner's lock.
  attempt=$((attempt + 1))
  [ "$attempt" -lt 10 ] || { echo "NFQUEUE bypass: $CMD update is busy" >&2; exit 1; }
  sleep 1
done
printf '%s\n' "$$" > "$lock/pid"
work=
swapped=0
stage_owned=0
probe_owned=0
cleanup() {
  result=$?
  trap - 0 HUP INT TERM
  if [ "$swapped" = 1 ]; then
    if ! ipset swap "$STAGE" "$SET"; then
      # Preserve the old set for recovery if the kernel rejects rollback.
      echo "NFQUEUE bypass: cannot roll back $SET; old addresses retained in $STAGE" >&2
      stage_owned=0
      result=1
    fi
  fi
  if [ "$probe_owned" = 1 ]; then
    $CMD -w -t "$TABLE" -F "$PROBE" 2>/dev/null || true
    $CMD -w -t "$TABLE" -X "$PROBE" 2>/dev/null || true
  fi
  [ "$stage_owned" != 1 ] || ipset destroy "$STAGE" 2>/dev/null || true
  if [ -n "$work" ]; then
    rm -f "$work/linear" "$work/sets" "$work/restore"
    rmdir "$work" 2>/dev/null || true
  fi
  rm -f "$lock/pid"
  rmdir "$lock" 2>/dev/null || true
  exit "$result"
}
trap cleanup 0
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# Do not flush a working chain if restore is absent or rejects a transaction.
command -v "$RESTORE" >/dev/null 2>&1 || { echo "NFQUEUE bypass: missing $RESTORE" >&2; exit 1; }
for parent in "$POST" "$PRE"; do
  $CMD -w -t "$TABLE" -L "$parent" -n >/dev/null 2>&1 ||
    { echo "NFQUEUE bypass: missing $CMD chain $parent" >&2; exit 1; }
done
work=$(mktemp -d "${TMPDIR:-/tmp}/nfqws-bypass.XXXXXX") || exit 1
: > "$work/linear"
: > "$work/sets"
set --
for file in "$LIST/nfqueue_bypass_ips.list" "$LIST/nfqueue_bypass_resolved.list"; do
  [ ! -r "$file" ] || set -- "$@" "$file"
done
# One parser process for the whole cache, without DNS or per-address forks.
# Keep linear rules available for kernels lacking hash:net or xt_set.
awk -v family="$FAMILY" -v chain="$BYPASS" -v stage="$STAGE" -v out="$work" '
function valid(ip, parts, n, a, count, i, groups, compressed) {
  n = split(ip, parts, "/")
  if (n > 2 || (n == 2 && parts[2] !~ /^[0-9]+$/)) return 0
  if (family == "inet") {
    if (n == 2 && parts[2] > 32) return 0
    count = split(parts[1], a, ".")
    if (count != 4) return 0
    for (i = 1; i <= count; i++) if (a[i] !~ /^[0-9]+$/ || a[i] > 255) return 0
  } else {
    if (n == 2 && parts[2] > 128) return 0
    if (parts[1] !~ /^[0-9A-Fa-f:]+$/ || parts[1] !~ /:/ || parts[1] ~ /:::/) return 0
    compressed = index(parts[1], "::")
    if (compressed && index(substr(parts[1], compressed + 2), "::")) return 0
    if ((parts[1] ~ /^:/ && parts[1] !~ /^::/) || (parts[1] ~ /:$/ && parts[1] !~ /::$/)) return 0
    count = split(parts[1], a, ":"); groups = 0
    for (i = 1; i <= count; i++) if (a[i] != "") {
      if (length(a[i]) > 4) return 0
      groups++
    }
    if ((compressed && groups >= 8) || (!compressed && groups != 8)) return 0
  }
  return 1
}
function add(ip) { if (!setseen[ip]++) print "add " stage " " ip >> (out "/sets") }
{
  sub(/[#;].*$/, ""); gsub(/^[ \t\r]+|[ \t\r]+$/, "")
  if (NF != 1 || !valid($0) || seen[$0]++) next
  # ACCEPT prevents returning to the NFQUEUE rule in the parent chain.
  print "-A " chain " -d " $0 " -j ACCEPT" >> (out "/linear")
  print "-A " chain " -s " $0 " -j ACCEPT" >> (out "/linear")
  split($0, p, "/")
  # hash:net excludes prefix zero. Two /1 networks have identical coverage.
  if (index($0, "/") && p[2] + 0 == 0) {
    if (family == "inet") { add("0.0.0.0/1"); add("128.0.0.0/1") }
    else { add("::/1"); add("8000::/1") }
  } else add($0)
}' "$@" </dev/null || exit 1

use_sets=0
if command -v ipset >/dev/null 2>&1; then
  # Only a previous interrupted invocation can leave this unreferenced set.
  ipset destroy "$STAGE" 2>/dev/null || true
  if ipset create "$STAGE" hash:net family "$FAMILY" hashsize 1024 maxelem 65536 2>/dev/null; then
    stage_owned=1
    # Probe kernel matching on an unattached private chain, never live traffic.
    if $CMD -w -t "$TABLE" -N "$PROBE" 2>/dev/null; then
      probe_owned=1
      if $CMD -w -t "$TABLE" -A "$PROBE" -m set --match-set "$STAGE" dst -j ACCEPT 2>/dev/null; then
        use_sets=1
      fi
      $CMD -w -t "$TABLE" -F "$PROBE" || exit 1
      $CMD -w -t "$TABLE" -X "$PROBE" || exit 1
      probe_owned=0
    fi
  fi
fi
printf '*%s\n:%s - [0:0]\n' "$TABLE" "$BYPASS" > "$work/restore"
if [ "$use_sets" = 1 ]; then
  ipset -exist restore < "$work/sets" || { echo "NFQUEUE bypass: cannot stage $SET" >&2; exit 1; }
  ipset list "$SET" >/dev/null 2>&1 ||
    ipset create "$SET" hash:net family "$FAMILY" hashsize 1024 maxelem 65536 || exit 1
  printf '%s\n' "-A $BYPASS -m set --match-set $SET dst -j ACCEPT" \
    "-A $BYPASS -m set --match-set $SET src -j ACCEPT" >> "$work/restore"
else
  cat "$work/linear" >> "$work/restore" || exit 1
fi
# Preserve existing jumps during refresh. New jumps commit with the chain,
# including after upstream recreates its chains during a firewall rebuild.
for parent in "$POST" "$PRE"; do
  if ! $CMD -w -t "$TABLE" -C "$parent" -j "$BYPASS" 2>/dev/null; then
    printf '%s\n' "-I $parent 1 -j $BYPASS" >> "$work/restore"
  fi
done
printf 'COMMIT\n' >> "$work/restore"
# Defer signals across swap/commit so cleanup sees the completed operation,
# including a successful commit whose child exits just as TERM arrives.
interrupted=0
trap 'interrupted=129' HUP
trap 'interrupted=130' INT
trap 'interrupted=143' TERM
if [ "$use_sets" = 1 ]; then
  ipset swap "$STAGE" "$SET" || { echo "NFQUEUE bypass: cannot swap $SET" >&2; exit 1; }
  swapped=1
fi
[ "$interrupted" = 0 ] || exit "$interrupted"
"$RESTORE" --noflush < "$work/restore" || { echo "NFQUEUE bypass: cannot commit $CMD rules; retaining previous policy" >&2; exit 1; }
swapped=0
[ "$interrupted" = 0 ] || exit "$interrupted"
if [ "$use_sets" = 0 ] && command -v ipset >/dev/null 2>&1; then
  ipset destroy "$SET" 2>/dev/null || true
fi

exit 0
`

// ensureBypassScript creates or upgrades our generated helper. Vendor helpers
// are preserved; older generated versions must be replaced so fixes reach
// routers that already applied bypass under a previous panel release.
func ensureBypassScript(name string) error {
	if err := os.MkdirAll(filepath.Dir(name), 0o755); err != nil {
		return err
	}
	if st, err := os.Stat(name); err == nil {
		if st.IsDir() {
			return os.ErrInvalid
		}
		current, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(current), "#!/bin/sh\n# Generated by nfqws2-strategy.") {
			if filepath.Base(name) == "nfqws-strategy-bypass.sh" {
				return fmt.Errorf("NFQUEUE bypass helper %s was modified outside the panel", name)
			}
			return os.Chmod(name, 0o755)
		}
		if string(current) == generatedBypassScript {
			return os.Chmod(name, 0o755)
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(name), ".nfqws-bypass-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(generatedBypassScript); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o755); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), name)
}

// ensureBypassPersistence installs the bypass after the platform's firewall
// rebuild hook.  Keenetic runs netfilter.d hooks in lexical order, so 101 runs
// after nfqws2's 100-nfqws2.sh has recreated its own chains.  OpenWrt uses a
// firewall4 script include instead.
func ensureBypassPersistence(confDir, initScript, bypassScript string) error {
	if !routerpath.IsOpenWrt() {
		return ensureKeeneticBypassPersistence(confDir, bypassScript)
	}
	if _, err := exec.LookPath("uci"); err != nil {
		return nil
	}
	hook := routerpath.Path(routerpath.NFQWSBypassFW4)
	if hook == "" || filepath.Dir(hook) != confDir {
		hook = filepath.Join(confDir, "nfqws-bypass-fw4.sh")
	}
	body := fmt.Sprintf("#!/bin/sh\n%s firewall_iptables >/dev/null 2>&1 || true\n%s firewall_ip6tables >/dev/null 2>&1 || true\n%s iptables >/dev/null || echo 'NFQUEUE bypass: IPv4 firewall reload failed' >&2\n%s ip6tables >/dev/null || echo 'NFQUEUE bypass: IPv6 firewall reload failed' >&2\n",
		shell.Quote(initScript), shell.Quote(initScript), shell.Quote(bypassScript), shell.Quote(bypassScript))
	if err := os.WriteFile(hook, []byte(body), 0o755); err != nil {
		return err
	}
	if err := os.Chmod(hook, 0o755); err != nil {
		return err
	}
	cmd := "uci -q show firewall.nfqws2_bypass_fw4 >/dev/null 2>&1 || uci set firewall.nfqws2_bypass_fw4=include; " +
		"uci set firewall.nfqws2_bypass_fw4.type=script; " +
		"uci set firewall.nfqws2_bypass_fw4.path=" + shell.Quote(filepath.ToSlash(hook)) + "; " +
		"uci set firewall.nfqws2_bypass_fw4.fw4_compatible=1; uci commit firewall"
	if out, err := exec.Command("sh", "-c", cmd).CombinedOutput(); err != nil {
		return fmt.Errorf("uci include: %v: %s", err, out)
	}
	return nil
}

const keeneticBypassHookName = "101-nfqws2-bypass.sh"

func keeneticBypassHookPath(confDir string) string {
	return filepath.Join(filepath.Dir(confDir), "ndm", "netfilter.d", keeneticBypassHookName)
}

func ensureKeeneticBypassPersistence(confDir, bypassScript string) error {
	hook := keeneticBypassHookPath(confDir)
	if err := os.MkdirAll(filepath.Dir(hook), 0o755); err != nil {
		return err
	}
	// The upstream 100-nfqws2.sh hook receives table/type from ndm and invokes
	// firewall_$type.  Run only for mangle, once those nfqws chains exist.  The
	// helper rebuilds both its jumps and destination rules idempotently.
	body := "#!/bin/sh\n" +
		"[ \"${table:-}\" = mangle ] || exit 0\n" +
		"case \"${type:-}\" in iptables|ip6tables) ;; *) exit 0 ;; esac\n" +
		"[ -x " + shell.Quote(bypassScript) + " ] || exit 0\n" +
		shell.Quote(bypassScript) + " \"$type\" >/dev/null || echo 'NFQUEUE bypass: Keenetic firewall reload failed' >&2\n"
	tmp, err := os.CreateTemp(filepath.Dir(hook), ".nfqws2-bypass-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(body); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o755); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), hook)
}

// ensureBypassInitHook keeps the dedicated jump alive across an NFQWS2
// restart on both OpenWrt and Keenetic.  Both upstream init scripts call
// system_config after rebuilding their firewall chains; the netfilter.d/fw4
// hooks only cover platform firewall reloads. Package updates are repaired by
// Manager.Update and the installer.
func ensureBypassInitHook(initScript, bypassScript string) error {
	return ensureBypassInitHookOn(initScript, bypassScript, true)
}

func ensureBypassInitHookOn(initScript, bypassScript string, enabled bool) error {
	if !enabled || initScript == "" || bypassScript == "" {
		return nil
	}
	b, err := os.ReadFile(initScript)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	const marker = "# nfqws2-strategy: reapply NFQUEUE bypass"
	text := string(b)
	line := marker + "\n[ -x " + shell.Quote(bypassScript) + " ] && " + shell.Quote(bypassScript) + " iptables >/dev/null 2>&1 || true\n[ -x " + shell.Quote(bypassScript) + " ] && " + shell.Quote(bypassScript) + " ip6tables >/dev/null 2>&1 || true"
	updated := ""
	if strings.Contains(text, marker) {
		// v1.6.5 and older pointed the tagged block at the vendor helper. Replace
		// only the two lines owned by this panel, keeping other init edits intact.
		lines := strings.SplitAfter(text, "\n")
		found := false
		for i, raw := range lines {
			if strings.TrimSpace(raw) != marker {
				continue
			}
			if i+2 >= len(lines) {
				return fmt.Errorf("NFQWS2 init has incomplete bypass hook")
			}
			for j, family := range []string{"iptables", "ip6tables"} {
				hookLine := strings.TrimSpace(lines[i+1+j])
				if !strings.HasPrefix(hookLine, "[ -x ") || !strings.Contains(hookLine, " ] && ") || !strings.Contains(hookLine, " "+family+" >/dev/null 2>&1 || true") {
					return fmt.Errorf("NFQWS2 init has unexpected bypass hook")
				}
			}
			oldBlock := lines[i] + lines[i+1] + lines[i+2]
			updated = strings.Replace(text, oldBlock, line+"\n", 1)
			found = true
			break
		}
		if !found {
			return fmt.Errorf("NFQWS2 init has unrecognized bypass marker")
		}
	} else {
		idx := -1
		offset := 0
		for _, raw := range strings.SplitAfter(text, "\n") {
			trimmed := strings.TrimSpace(raw)
			if strings.HasPrefix(trimmed, "system_config") && !strings.Contains(trimmed, "()") && !strings.HasSuffix(trimmed, "{") {
				idx = offset
				break
			}
			offset += len(raw)
		}
		if idx < 0 {
			return fmt.Errorf("NFQWS2 init has no system_config post-start anchor")
		}
		end := strings.IndexByte(text[idx:], '\n')
		if end < 0 {
			return fmt.Errorf("NFQWS2 init has malformed system_config line")
		}
		insertAt := idx + end + 1
		updated = text[:insertAt] + line + "\n" + text[insertAt:]
	}
	if updated == text {
		return nil
	}
	// Keep one pristine copy for rollback. The temporary replacement must have
	// a different name; otherwise a successful rename would remove the backup
	// and leave only the already patched script behind.
	backup := initScript + ".n2s-bak"
	if _, statErr := os.Stat(backup); os.IsNotExist(statErr) {
		file, createErr := os.OpenFile(backup, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o755)
		if createErr != nil && !os.IsExist(createErr) {
			return createErr
		}
		if createErr == nil {
			if _, writeErr := file.Write(b); writeErr != nil {
				_ = file.Close()
				_ = os.Remove(backup)
				return writeErr
			}
			if closeErr := file.Close(); closeErr != nil {
				_ = os.Remove(backup)
				return closeErr
			}
		}
		if err := os.Chmod(backup, 0o755); err != nil {
			return err
		}
	} else if statErr != nil {
		return statErr
	}
	tmpFile, err := os.CreateTemp(filepath.Dir(initScript), filepath.Base(initScript)+".n2s-new-")
	if err != nil {
		return err
	}
	tmp := tmpFile.Name()
	if _, err := tmpFile.Write([]byte(updated)); err != nil {
		_ = tmpFile.Close()
		_ = os.Remove(tmp)
		return err
	}
	if err := tmpFile.Close(); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Chmod(tmp, 0o755); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	if err := os.Rename(tmp, initScript); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return nil
}

// removeBypassPersistence is used by the package uninstaller on both router
// families.  Only the hook owned by this package is removed.
func removeBypassPersistence(confDir string) {
	_ = os.Remove(filepath.Join(confDir, "nfqws-bypass-fw4.sh"))
	_ = os.Remove(keeneticBypassHookPath(confDir))
	if _, err := exec.LookPath("uci"); err == nil {
		_, _ = exec.Command("sh", "-c", "uci -q delete firewall.nfqws2_bypass_fw4 2>/dev/null || true; uci commit firewall 2>/dev/null || true").CombinedOutput()
	}
}
